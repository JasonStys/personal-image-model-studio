    def request_close(self) -> None:
        """Use the same completion gate for Quit, OS close and explicit synthetic acceptance input."""
        self.closing = True
        self.open_button.state(["disabled"])
        self.quit_button.state(["disabled"])
        self.status.set(
            "Closing after active local requests finish. Saved accounts and vaults are retained."
        )
        self.service.request_stop()

    def show_notices(self) -> None:
        """Show verified local runtime license text in an owned scrollable native window."""
        window = tk.Toplevel(self.root)
        window.title("Bundled runtime notices · Jason Stys")
        window.geometry("800x600")
        frame = ttk.Frame(window, padding=16)
        frame.pack(fill="both", expand=True)
        content = tk.Text(frame, wrap="word", font=("Consolas", 10))
        scrollbar = ttk.Scrollbar(frame, orient="vertical", command=content.yview)
        content.configure(yscrollcommand=scrollbar.set)
        scrollbar.pack(side="right", fill="y")
        content.pack(fill="both", expand=True)
        content.insert("1.0", self.notices)
        content.configure(state="disabled")
        ttk.Button(frame, text="Close notices", command=window.destroy).pack(
            anchor="e", pady=(10, 0)
        )

    def poll(self) -> None:
        """Observe service lifecycle and queued input; other threads never manipulate widgets."""
        try:
            while self.commands.get_nowait() == "quit":
                self.request_close()
        except queue.Empty:
            pass
        if self.service.server.started and not self.ready and not self.closing:
            self.ready = True
            self.open_button.state(["!disabled"])
            self.status.set(f"Ready at {self.service.origin}. Use Quit application to stop safely.")
            print(
                f"Personal Image Model Studio by Jason Stys is running at {self.service.origin}",
                flush=True,
            )
            if self.open_browser:
                self.open()
        if self.service.done.is_set():
            if self.service.failed or (not self.ready and not self.closing):
                self.service.failed = True
                messagebox.showerror(
                    "Personal Image Model Studio",
                    "The local service stopped unexpectedly. Saved accounts were not reset.",
                    parent=self.root,
                )
            self.root.destroy()
            return
        self.root.after(50, self.poll)

    def acceptance_input(self, nonce: str) -> None:
        """Enable one bounded stdin command only in explicitly configured synthetic acceptance mode."""
        if re.fullmatch(r"[a-f0-9]{64}", nonce) is None or sys.stdin is None:
            raise ValueError("Invalid explicit native acceptance channel")

        def receive() -> None:
            """Read only the exact nonce-authorized Quit command; never accept input paths or executable code."""
            try:
                if sys.stdin.readline(96) == f"quit {nonce}\n":
                    self.commands.put("quit")
            except (OSError, ValueError):
                return

        threading.Thread(
            target=receive, name="pims-synthetic-acceptance-input", daemon=True
        ).start()
