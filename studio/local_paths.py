from __future__ import annotations

import os
import re
from pathlib import Path


def canonical_id(value: str) -> str:
    """Accept only the exact lowercase UUID32 grammar generated by this application before any lookup."""
    if not isinstance(value, str) or re.fullmatch(r"[a-f0-9]{32}", value) is None:
        raise KeyError("Unknown workspace artifact")
    return value


class LocalPaths:
    """Constrain privileged legacy selections to independently configured, component-safe local roots."""

    def __init__(self, roots: tuple[Path, ...]):
        """Only trusted launcher/application construction supplies roots; filesystem roots are not grants."""
        if not roots or len(roots) > 32:
            raise ValueError("Configure between one and 32 approved local roots")
        normalized = []
        for root in roots:
            value = os.path.normcase(os.path.realpath(os.fspath(root)))
            if value == os.path.dirname(value) or value.startswith(("\\\\", "//")):
                raise ValueError("A filesystem or network root cannot be an import grant")
            normalized.append(value)
        self.roots = tuple(dict.fromkeys(normalized))

    def selected(self, value: str | Path) -> Path:
        """Normalize links first, then require equality or a complete separator-delimited granted prefix."""
        raw = os.fspath(value)
        if not isinstance(raw, str) or not raw or len(raw) > 4096 or any(ord(c) < 32 for c in raw):
            raise ValueError("Invalid local selection")
        if raw.startswith(("\\\\", "//")):
            raise ValueError("Network/device selections are not supported")
        resolved = os.path.realpath(raw)
        comparable = os.path.normcase(resolved)
        for root in self.roots:
            # This is an independent launcher-owned root, never the parent of caller input.
            if comparable == root or comparable.startswith(root + os.sep):
                return Path(resolved)
        raise ValueError(
            "Selection is outside approved local roots; configure an owner-approved root in the legacy launcher"
        )
